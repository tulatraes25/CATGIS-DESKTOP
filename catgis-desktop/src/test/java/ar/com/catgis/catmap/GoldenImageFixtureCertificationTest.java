package ar.com.catgis.catmap;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

class GoldenImageFixtureCertificationTest {

    private static final String RESOURCE_PREFIX = "ar/com/catgis/catmap/golden/";

    @Test
    void everyActiveGoldenComparisonHasAnExistingReadableReference() throws Exception {
        List<String> names = List.of(
                "label.png",
                "shapes.png",
                "scalebar.png",
                "north.png",
                "legend.png",
                "cartouche.png",
                "pipeline.png",
                "map-preview.png",
                "pipeline-map.png",
                "catmap-real-data.png",
                "catmap-real-rendered.png"
        );

        for (String name : names) {
            try (InputStream input = GoldenImageFixtureCertificationTest.class
                    .getClassLoader().getResourceAsStream(RESOURCE_PREFIX + name)) {
                assertNotNull(input, "Missing committed CATMAP golden fixture: " + name);
                BufferedImage image = ImageIO.read(input);
                assertNotNull(image, "Invalid CATMAP golden PNG: " + name);
                assertTrue(image.getWidth() > 0 && image.getHeight() > 0,
                        "Empty CATMAP golden reference: " + name);
            }
        }
    }

    @Test
    void comparisonsMustNeverGenerateMissingBaselinesOnTheFly() throws Exception {
        Path testSource = Path.of("src", "test", "java", "ar", "com", "catgis", "catmap",
                "GoldenImageTest.java");
        String source = Files.readString(testSource, StandardCharsets.UTF_8);
        assertFalse(source.contains("saveGoldenImage("),
                "CATMAP golden baselines must be explicitly reviewed and checked in, not generated by a passing test.");
        Path realDataTestSource = Path.of("src", "test", "java", "ar", "com", "catgis",
                "catmap", "CatmapVisualTest.java");
        String realDataSource = Files.readString(realDataTestSource, StandardCharsets.UTF_8);
        assertFalse(realDataSource.contains("saveGoldenImage("),
                "CATMAP real-data golden baselines must never be generated by a passing test.");
    }
}
